const EMOJI_CATEGORIES = Object.keys(EMOJI_DATA);

window.DailyApp = window.DailyApp || {};
DailyApp.emojiPicker = {

  showEmojiPicker: false,
  emojiPickerTarget: null,     // properti Alpine yang akan diisi
  emojiSearch: '',
  emojiActiveCategory: 'Smiley',

  /* --- Computed: filter emoji by search + category --- */
  getFilteredEmojis() {
    const search = (this.emojiSearch || '').toLowerCase().trim();

    if (!search) {
      return EMOJI_DATA[this.emojiActiveCategory] || [];
    }

    // Jika ada search: cari di SEMUA kategori, tampilkan emoji dari kategori yg cocok
    const matchedCategories = EMOJI_CATEGORIES.filter(cat =>
      cat.toLowerCase().includes(search)
    );
    const results = [];
    matchedCategories.forEach(cat => {
      EMOJI_DATA[cat].forEach(emoji => results.push(emoji));
    });
    return results;
  },

  get emojiCategories() {
    return EMOJI_CATEGORIES;
  },

  /* --- Buka picker --- */
  openEmojiPicker(targetProp) {
    this.emojiPickerTarget = targetProp;
    this.emojiSearch = '';
    this.emojiActiveCategory = 'Smiley';
    this.showEmojiPicker = true;
  },

  /* --- Pilih emoji --- */
  selectEmoji(emoji) {
    // Jika dalam mode mood customization
    if (this.moodEmojiPickKey) {
      this.saveCustomEmoji(this.moodEmojiPickKey, emoji);
      this.moodEmojiPickKey = null;
      this.showEmojiPicker = false;
      this.emojiPickerTarget = null;
      return;
    }
    // Default: isi properti target
    if (this.emojiPickerTarget && this[this.emojiPickerTarget] !== undefined) {
      this[this.emojiPickerTarget] = emoji;
    }
    this.showEmojiPicker = false;
    this.emojiPickerTarget = null;
  },

  /* --- Tutup picker --- */
  closeEmojiPicker() {
    this.showEmojiPicker = false;
    this.emojiPickerTarget = null;
  },
};
